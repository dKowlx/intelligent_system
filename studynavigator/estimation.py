"""Shared model instructions: effort is a reasoned estimate, never source fact."""

import re


def is_reestimate_request(message):
    """Route an explicit effort review to theory retrieval, never apply edits.

    A numeric replacement ("поставь 90 минут") is already handled by the
    deterministic user-edit path. This detector requests model reasoning.
    """
    if not isinstance(message, str):
        return False
    text = message.casefold().replace("ё", "е")
    if re.search(r"\bне\s+(?:надо\s+|нужно\s+)?(?:переоц|пересчит|оцени|оценив|меня|измен)", text):
        return False
    effort = re.search(r"врем|длительност|трудоемкост|оценк|минут|час|действи|задач|шаг", text)
    request = re.search(r"\b(?:переоцени(?:ть)?|пересчитай|пересчитать|переоценка|переоценку)\b", text)
    fresh = re.search(r"\b(?:оцени|оценить|рассчитай|рассчитать)\b", text) and re.search(
        r"заново|реалистич|адекватн|сложност|подготовк|проверк|решени", text)
    return bool(effort and (request or fresh))


